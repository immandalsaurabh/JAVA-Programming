public class Operators {
    public static void main(String[] args) {
        int a = 20;
        int b = 6;

        // Addition
        int sumResult = a + b;
        System.out.println(sumResult);

        // Subtraction
        int subResult = a - b;
        System.out.println(subResult);

        // Multiplication
        int mulResult = a * b;
        System.out.println(mulResult);

        // Divison
        int divResult = a / b;
        System.out.println(divResult);

        // Moduls
        int modResult = a % b;
        System.out.println(modResult);
    }

}
